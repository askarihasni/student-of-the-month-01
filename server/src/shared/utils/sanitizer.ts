import sanitizeHtml from 'sanitize-html';

export function sanitizeSvg(svgContent: string): string {
  // Clean SVG markup: strip any script, iframe, foreignObject, event handlers, and javascript: URIs
  const clean = sanitizeHtml(svgContent, {
    allowedTags: [
      'svg',
      'g',
      'path',
      'rect',
      'circle',
      'ellipse',
      'line',
      'polyline',
      'polygon',
      'text',
      'tspan',
      'defs',
      'linearGradient',
      'radialGradient',
      'stop',
      'mask',
      'clipPath',
      'use',
    ],
    allowedAttributes: {
      '*': [
        'id',
        'class',
        'fill',
        'stroke',
        'stroke-width',
        'stroke-linecap',
        'stroke-linejoin',
        'opacity',
        'transform',
        'd',
        'x',
        'y',
        'width',
        'height',
        'cx',
        'cy',
        'r',
        'rx',
        'ry',
        'x1',
        'y1',
        'x2',
        'y2',
        'viewbox',
        'viewBox',
        'xmlns',
        'points',
        'font-family',
        'font-size',
        'font-weight',
        'text-anchor',
        'offset',
        'stop-color',
        'stop-opacity',
      ],
    },
    allowedSchemes: ['http', 'https'],
    disallowedTagsMode: 'discard',
  });

  return clean;
}
